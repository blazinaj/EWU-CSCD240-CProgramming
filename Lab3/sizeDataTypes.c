#include <stdio.h>

int main() {
  printf("The size of a short is %zu \n", sizeof(short));
  printf("The size of an int is %zu \n", sizeof(int));
  printf("The size of a char is %zu \n", sizeof(char));
  printf("The size of a double is %zu \n", sizeof(double));
  printf("The size of a long is %zu \n", sizeof(long));
  printf("The size of a long double is %zu \n", sizeof(long double)); 

  return 0;
}
